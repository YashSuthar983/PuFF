import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('./', import.meta.url);
// Dependency order; each module keeps its private shader names in its own scope.
const modules = ['config.js', 'volume.js', 'lightning.js', 'fields.js', 'time.js', 'scene.js', 'text.js'];
const { version } = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
let bundle = `/* PuFF ${version} — generated by build.mjs. */\n(function(scope){\n"use strict";\nconst kit={};\n`;
for (const file of modules) {
  const source = await readFile(new URL(`src/${file}`, root), 'utf8');
  const exports = [...source.matchAll(/^export (?:class|function|const) (\w+)/gm)].map(match => match[1]);
  const body = source
    .replace(/^import \{([^}]+)\} from '\.\/[^']+';$/gm, 'const {$1} = kit;')
    .replace(/^export (class|function|const) /gm, '$1 ');
  bundle += `Object.assign(kit,(function(){\n${body}\nreturn {${exports.join(',')}};\n})());\n`;
}
bundle += 'scope.PuFF=kit;\n})(typeof window!=="undefined"?window:globalThis);\n';
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/puff.js', root), bundle);
console.log('Built PuFF browser bundle.');
