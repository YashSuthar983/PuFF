import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
const root=new URL('./',import.meta.url);
const components=[['config.js','CloudControls'],['volume.js','CloudVolume'],['lightning.js','Lightning'],['fields.js','createDensityField'],['time.js','CloudTimes'],['scene.js','CloudScene'],['text.js','CloudText']];
const {version}=JSON.parse(await readFile(new URL('package.json',root),'utf8'));
let bundle=`/* Cloud Kit ${version} — generated by cloud-library/build.mjs. */\n(function(scope){\n"use strict";\nconst kit={};\n`;
for(const [file,name] of components){
  const source=(await readFile(new URL(`src/${file}`,root),'utf8')).replace(/^import .*;\s*$/gm,'').replace(/export (class|function|const) /g,'$1 ');
  const scene=name==='CloudScene';
  bundle+=`${scene?'Object.assign(kit,':'kit.'+name+'='}(function(){\n${name==='CloudText'?'const CloudVolume=kit.CloudVolume;const CloudTimes=kit.CloudTimes;const CloudControls=kit.CloudControls;\n':''}${scene?'const Lightning=kit.Lightning;const CloudTimes=kit.CloudTimes;\n':''}${['CloudScene','CloudVolume','Lightning'].includes(name)?'const CloudControls=kit.CloudControls;\n':''}${source}\nreturn ${scene?'{CloudScene,StormClouds,CloudPresets}':name};})()${scene?')':''};\n`;
}
bundle+='scope.CloudKit=kit;\n})(typeof window!=="undefined"?window:globalThis);\n';
await mkdir(new URL('dist/',root),{recursive:true});
await writeFile(new URL('dist/cloud-kit.js',root),bundle);
try {
  await access(new URL('../port_v2/',root));
  await writeFile(new URL('../port_v2/cloud-volume.js',root),'/* Portfolio adapter. Engine source: cloud-library/src/volume.js. */\nwindow.CloudVolume=window.CloudKit.CloudVolume;\n');
  await writeFile(new URL('../port_v2/sky-lightning.js',root),'/* Portfolio adapter. Engine source: cloud-library/src/lightning.js. */\nwindow.SkyLightning=window.CloudKit.Lightning;\n');
} catch(error) { if(error.code!=='ENOENT')throw error; }
console.log('Built CloudKit browser bundle.');
