#!/usr/bin/env python3
"""Generate our own tileable volcanic-rock PBR maps (backup for the downloaded scan).

Height = angular plates (Voronoi cells, each a randomly tilted plane) + fractal detail,
with grooves along plate borders. Normal, roughness and albedo derive from it.
Writes albedo/normal/roughness/height .webp plus embedded-maps.js (data URLs, for file://).

    python3 tools/generate-rock-texture.py [output_dir] [--size 1024] [--seed 7]
Needs numpy and Pillow.
"""
import argparse, base64, json, os
import numpy as np
from PIL import Image

def tile_noise(rng, size, cells):
    """Tileable value noise: random lattice, bicubic-ish (smoothstep) interpolation with wraparound."""
    grid = rng.random((cells, cells))
    t = np.arange(size) * cells / size
    i0 = np.floor(t).astype(int); f = t - i0; f = f * f * (3 - 2 * f); i1 = (i0 + 1) % cells
    rows = grid[i0][:, i0] * (1 - f)[None, :] + grid[i0][:, i1] * f[None, :]
    rows1 = grid[i1][:, i0] * (1 - f)[None, :] + grid[i1][:, i1] * f[None, :]
    return rows * (1 - f)[:, None] + rows1 * f[:, None]

def fbm(rng, size, base, octaves, gain=.5):
    out = np.zeros((size, size)); amp = 1; total = 0
    for o in range(octaves):
        out += tile_noise(rng, size, base * 2 ** o) * amp; total += amp; amp *= gain
    return out / total

def plates(rng, size, count, warp):
    """Voronoi plates on a torus. Each cell is a tilted plane, so faces are flat and borders crease."""
    pts = rng.random((count, 2)); tilt = (rng.random((count, 2)) - .5) * 9; lift = rng.random(count)
    y, x = np.mgrid[0:size, 0:size] / size
    x = (x + warp[0]) % 1; y = (y + warp[1]) % 1
    f1 = np.full((size, size), 9.); f2 = np.full((size, size), 9.); owner = np.zeros((size, size), int)
    dx_own = np.zeros((size, size)); dy_own = np.zeros((size, size))
    for k, (px, py) in enumerate(pts):
        dx = (x - px + .5) % 1 - .5; dy = (y - py + .5) % 1 - .5   # wrapped offsets keep it tileable
        d = np.sqrt(dx * dx + dy * dy)
        closer = d < f1
        f2 = np.where(closer, f1, np.minimum(f2, d)); f1 = np.where(closer, d, f1)
        owner = np.where(closer, k, owner); dx_own = np.where(closer, dx, dx_own); dy_own = np.where(closer, dy, dy_own)
    height = lift[owner] * .5 + tilt[owner, 0] * dx_own + tilt[owner, 1] * dy_own
    return height, f2 - f1

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out', nargs='?', default=os.path.join(os.path.dirname(__file__), '..', 'assets', 'rock-generated'))
    ap.add_argument('--size', type=int, default=1024); ap.add_argument('--seed', type=int, default=7)
    a = ap.parse_args(); n = a.size; rng = np.random.default_rng(a.seed); os.makedirs(a.out, exist_ok=True)

    warp = ((fbm(rng, n, 4, 4) - .5) * .06, (fbm(rng, n, 4, 4) - .5) * .06)
    big, edge_big = plates(rng, n, 26, warp)
    small, edge_small = plates(rng, n, 140, warp)
    detail = fbm(rng, n, 16, 5)
    grooves = np.exp(-edge_big / .006) * .9 + np.exp(-edge_small / .003) * .22      # plate borders become cracks
    h = big * .55 + small * .22 + detail * .3 - grooves * .35
    lo, hi = np.percentile(h, [.5, 99.5]); h = np.clip((h - lo) / (hi - lo), 0, 1)

    # Normal from wrapped central differences (OpenGL convention, +Y up).
    strength = n / 160
    gx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) * strength; gy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) * strength
    nrm = np.stack([-gx, gy, np.ones_like(h)], -1); nrm /= np.linalg.norm(nrm, axis=-1, keepdims=True)

    cavity = np.clip(1 - grooves * .8, 0, 1)
    tone = .32 + .3 * fbm(rng, n, 8, 4) + .25 * h
    albedo = np.clip(tone * cavity, 0, 1)[..., None] * np.array([.95, .97, 1.])          # neutral basalt grey
    rough = np.clip(.78 - .3 * h + .15 * (fbm(rng, n, 32, 3) - .5) + grooves * .2, .2, 1)

    def save(arr, name, mode):
        Image.fromarray((np.clip(arr, 0, 1) * 255 + .5).astype(np.uint8), mode).save(os.path.join(a.out, name), 'WEBP', quality=92, method=6)
    save(albedo, 'albedo.webp', 'RGB'); save(nrm * .5 + .5, 'normal.webp', 'RGB'); save(rough, 'roughness.webp', 'L'); save(h, 'height.webp', 'L')
    key = os.path.basename(os.path.normpath(a.out))
    maps = {name: 'data:image/webp;base64,' + base64.b64encode(open(os.path.join(a.out, name), 'rb').read()).decode()
            for name in ['albedo.webp', 'normal.webp', 'roughness.webp', 'height.webp']}
    with open(os.path.join(a.out, 'embedded-maps.js'), 'w') as f:
        f.write('// Generated by tools/generate-rock-texture.py (seed %d) for origin-clean file:// previews.\n' % a.seed)
        f.write('(window.EmeraldMapSets=window.EmeraldMapSets||{})[%s]=%s;\n' % (json.dumps(key), json.dumps(maps)))
    for name in sorted(os.listdir(a.out)): print(name, os.path.getsize(os.path.join(a.out, name)))

if __name__ == '__main__':
    main()
