#!/usr/bin/env python3
"""Convert downloaded Poly Haven 'Rock Face 03' 1k PNG maps (CC0) into the WebP set used by the cliff.

    python3 tools/convert-rock.py <folder with diff/nor_gl/rough/disp/ao .png> assets/rock
Source: https://polyhaven.com/a/rock_face_03 (Dario Barresi, Rico Cilliers). Needs numpy and Pillow.
"""
import sys,os,base64,json
import numpy as np
from PIL import Image
src,dst=sys.argv[1],sys.argv[2]
os.makedirs(dst,exist_ok=True)
def load(name):
    im=Image.open(os.path.join(src,name))
    a=np.asarray(im).astype(np.float64)
    return a/(65535. if a.max()>255 else 255.)
diff,nor,rough,disp,ao=[load(n+'.png') for n in ['diff','nor_gl','rough','disp','ao']]
print('ranges',[ (round(x.min(),3),round(x.max(),3)) for x in (diff,nor,rough,disp,ao)])
lum=lambda a:a if a.ndim==2 else a[...,:3].mean(-1)
alb=diff[...,:3]*lum(ao)[...,None]
d=lum(disp);lo,hi=np.percentile(d,[.5,99.5]);d=np.clip((d-lo)/(hi-lo),0,1)
save=lambda a,n,mode:Image.fromarray((np.clip(a,0,1)*255+.5).astype(np.uint8),mode).save(os.path.join(dst,n),'WEBP',quality=92,method=6)
save(alb,'albedo.webp','RGB');save(nor[...,:3],'normal.webp','RGB');save(lum(rough),'roughness.webp','L');save(d,'height.webp','L')
maps={n:'data:image/webp;base64,'+base64.b64encode(open(os.path.join(dst,n),'rb').read()).decode() for n in ['albedo.webp','normal.webp','roughness.webp','height.webp']}
key=os.path.basename(os.path.normpath(dst))
open(os.path.join(dst,'embedded-maps.js'),'w').write('// Generated by tools/convert-rock.py from the maps beside this file, for origin-clean file:// previews.\n(window.EmeraldMapSets=window.EmeraldMapSets||{})['+json.dumps(key)+']='+json.dumps(maps)+';\n')
for n in sorted(os.listdir(dst)):print(n,os.path.getsize(os.path.join(dst,n)))
