"""Convert a trophy FBX into the Emerald 3D model format. Runs inside Blender:

    blender -b --python tools/convert-trophy.py -- model.fbx assets/trophy

The FBX holds a glass body mesh and, optionally, a "Faceplate" quad whose material carries the
engraving image. Writes:
  trophy.js       window.EmeraldTrophyModel = {positions, normals, indices, planes, plate, bounds}
                  (a script, not JSON, so it also loads from file://)
  faceplate.webp  the engraving, from the faceplate material's image (also embedded in trophy.js)

Space: Blender Z-up becomes Y-up, the faceplate side faces +Z (the camera), the body is centred
on the origin and scaled to 3 units tall. Faces are split so bevels stay crisp. `planes` are the
body's distinct face planes (n.xyz, d), used to find where a refracted ray leaves a convex body.
"""
import bpy, sys, os, json, math
import mathutils

args = sys.argv[sys.argv.index('--') + 1:]
src, out = args[0], args[1] if len(args) > 1 else os.path.join(os.path.dirname(__file__), '..', 'assets', 'trophy')
os.makedirs(out, exist_ok=True)
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.fbx(filepath=os.path.abspath(src))

meshes = [o for o in bpy.data.objects if o.type == 'MESH']
plate_obj = next((o for o in meshes if 'faceplate' in o.name.lower() or len(o.data.polygons) <= 2), None)
body = max((o for o in meshes if o is not plate_obj), key=lambda o: len(o.data.vertices))
to_y_up = lambda v: mathutils.Vector((v.x, v.z, -v.y))

def world_verts(o):
    return [to_y_up(o.matrix_world @ v.co) for v in o.data.vertices]

bv = world_verts(body)
lo = mathutils.Vector([min(v[i] for v in bv) for i in range(3)]); hi = mathutils.Vector([max(v[i] for v in bv) for i in range(3)])
centre = (lo + hi) / 2; scale = 3. / (hi.y - lo.y)
# Faceplate side should face +Z. If the plate sits on the -Z side, turn the model around.
flip = 1.
if plate_obj:
    pz = sum(v.z for v in world_verts(plate_obj)) / len(plate_obj.data.vertices)
    flip = 1. if pz >= centre.z else -1.
norm = lambda v: mathutils.Vector(((v.x - centre.x) * scale * flip, (v.y - centre.y) * scale, (v.z - centre.z) * scale * flip))

positions, normals, indices, planes = [], [], [], []
nm = body.matrix_world.to_3x3().inverted().transposed()
for poly in body.data.polygons:
    pts = [norm(bv[i]) for i in poly.vertices]
    n = to_y_up(nm @ poly.normal); n = mathutils.Vector((n.x * flip, n.y, n.z * flip)).normalized()
    base = len(positions) // 3
    for p in pts: positions += [p.x, p.y, p.z]; normals += [n.x, n.y, n.z]
    for k in range(1, len(pts) - 1): indices += [base, base + k, base + k + 1]   # fan; faces are convex
    d = n.dot(pts[0])
    if not any((mathutils.Vector(q[:3]) - n).length < 1e-3 and abs(q[3] - d) < 2e-3 for q in planes):
        planes.append([n.x, n.y, n.z, d])

verts = [norm(v) for v in bv]
convex = all(mathutils.Vector(q[:3]).dot(v) <= q[3] + 1e-3 for q in planes for v in verts)
half = [(hi[i] - lo[i]) / 2 * scale for i in range(3)]
model = {'positions': [round(x, 5) for x in positions], 'normals': [round(x, 5) for x in normals], 'indices': indices,
         'planes': [[round(x, 5) for x in q] for q in planes], 'half': [round(x, 5) for x in half], 'convex': convex}

if plate_obj:
    pv = [norm(v) for v in world_verts(plate_obj)]
    model['plate'] = {'rect': [round(min(v.x for v in pv), 5), round(min(v.y for v in pv), 5), round(max(v.x for v in pv), 5), round(max(v.y for v in pv), 5)],
                      'z': round(sum(v.z for v in pv) / len(pv), 5)}
    image = next((n.image for m in plate_obj.data.materials if m and m.node_tree for n in m.node_tree.nodes if n.type == 'TEX_IMAGE' and n.image), None)
    if image:
        png = os.path.join(out, '_faceplate.png'); image.save(filepath=png)
        try:   # Blender's bundled Python usually lacks Pillow: then hand the PNG to the system python3.
            from PIL import Image as PILImage
            PILImage.open(png).convert('L').save(os.path.join(out, 'faceplate.webp'), 'WEBP', quality=90, method=6)
        except ImportError:
            import subprocess
            subprocess.run(['python3', '-I', '-c', "import sys;from PIL import Image;Image.open(sys.argv[1]).convert('L').save(sys.argv[2],'WEBP',quality=90,method=6)",
                            png, os.path.join(out, 'faceplate.webp')], check=True)
        os.remove(png)
        # Embed as a data URL: a file:// page can then upload it to WebGL without tainting the canvas.
        import base64
        webp = os.path.join(out, 'faceplate.webp')
        model['plate']['src'] = 'data:image/webp;base64,' + base64.b64encode(open(webp, 'rb').read()).decode()

with open(os.path.join(out, 'trophy.js'), 'w') as f:
    f.write('// Generated by tools/convert-trophy.py from %s. Y-up, faceplate toward +Z, 3 units tall.\n' % os.path.basename(src))
    f.write('window.EmeraldTrophyModel=%s;\n' % json.dumps(model, separators=(',', ':')))
print('TROPHY', len(positions) // 3, 'verts', len(indices) // 3, 'tris', len(planes), 'planes', 'convex' if convex else 'NOT convex', 'half', model['half'], 'plate', {k: v for k, v in model.get('plate', {}).items() if k != 'src'})
